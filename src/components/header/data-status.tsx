"use client";

import { AlertTriangle, CircleDot, Loader2, WifiOff } from "lucide-react";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import { formatUtcTime } from "@/lib/radar/frames";
import { useRadarCatalogStatus } from "@/lib/radar/use-radar-catalog";
import { useNowSeconds } from "@/lib/use-now";
import { useAtmosStore } from "@/store/atmos-store";
import { cn } from "@/lib/utils";

/** Metadata considered stale after this long without a successful refresh. */
const STALE_AFTER_S = 12 * 60;

export function DataStatus() {
  const { data, error: finalError, failureReason, isError, dataUpdatedAt, isFetching } = useRadarCatalogStatus();
  // TanStack only sets `error` after every retry has failed (minutes, with
  // rate-limit backoff). `failureReason` is the latest failure while retrying.
  const error = finalError ?? failureReason;
  const now = useNowSeconds();
  const budget = useAtmosStore((s) => s.budget);

  let tone: "muted" | "ok" | "warn" | "error" = "muted";
  let label = "Loading radar…";
  let detail = "Requesting the list of available radar frames.";
  let Icon = Loader2;
  let listPrefix = false;

  if (data) {
    const updatedS = Math.floor(dataUpdatedAt / 1000);
    const stale = isError || !!failureReason || (now > 0 && now - updatedS > STALE_AFTER_S);
    if (stale) {
      tone = "warn";
      Icon = AlertTriangle;
      label = "Stale data";
      detail = `Last successful update ${formatUtcTime(updatedS)} UTC.${error ? ` ${error.message}` : ""} Retrying automatically.`;
    } else {
      tone = "ok";
      Icon = CircleDot;
      label = `${formatUtcTime(data.generatedAt)} UTC`;
      listPrefix = true;
      detail = `Frame list generated by the provider at ${formatUtcTime(data.generatedAt)} UTC. Refreshes about every 5 minutes.`;
    }
  } else if (error) {
    tone = "error";
    Icon = WifiOff;
    label = "Radar unavailable";
    detail = `${error?.message ?? "Request failed."} The basemap still works; retrying with backoff.`;
  }

  // Uses the coarse clock rather than Date.now() so rendering stays pure.
  const cooling = now > 0 && budget.cooldownUntil > now * 1000;

  return (
    <div className="flex min-w-0 items-center gap-2">
      <Tooltip>
        <TooltipTrigger
          render={
            <span
              role="status"
              aria-live="polite"
              tabIndex={0}
              className={cn(
                "inline-flex min-w-0 items-center gap-1.5 rounded-md px-2 py-1 text-xs outline-none focus-visible:ring-2 focus-visible:ring-ring",
                tone === "ok" && "text-emerald-300",
                tone === "warn" && "bg-amber-500/10 text-amber-300",
                tone === "error" && "bg-red-500/10 text-red-300",
                tone === "muted" && "text-muted-foreground",
              )}
            />
          }
        >
          <Icon className={cn("size-3.5 shrink-0", Icon === Loader2 && "animate-spin")} aria-hidden />
          <span className="truncate">
            {listPrefix ? <span className="sr-only sm:not-sr-only">Radar list </span> : null}
            {label}
          </span>
          {isFetching && data ? <span className="sr-only"> (refreshing)</span> : null}
        </TooltipTrigger>
        <TooltipContent className="max-w-xs">{detail}</TooltipContent>
      </Tooltip>
      {budget.limit > 0 ? (
        <Tooltip>
          <TooltipTrigger
            render={
              <span
                tabIndex={0}
                className={cn(
                  "hidden rounded-md px-1.5 py-1 font-mono text-[11px] tabular-nums outline-none focus-visible:ring-2 focus-visible:ring-ring lg:inline",
                  cooling || budget.used >= budget.limit ? "text-amber-300" : "text-muted-foreground",
                )}
              />
            }
          >
            {budget.used}/{budget.limit} req/min
          </TooltipTrigger>
          <TooltipContent className="max-w-xs">
            New provider requests in the last 60 s (tiles + metadata), against a self-imposed
            budget below RainViewer&apos;s documented 100/min limit.
            {cooling ? " The provider asked us to slow down; loading is paused briefly." : ""}
          </TooltipContent>
        </Tooltip>
      ) : null}
    </div>
  );
}
